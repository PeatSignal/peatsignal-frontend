import assert from "node:assert/strict";
import test from "node:test";
import { chromium } from "playwright";
import { signIn, switchRole } from "./helpers.mjs";
import { selectOption } from "../helpers/select.mjs";

const baseURL = process.env.SHELL_BASE_URL ?? "http://127.0.0.1:3000";

test("masyarakat: portal khusus, peta, peringatan, laporan persisten, dan akses role", { timeout: 120_000 }, async (t) => {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  t.after(() => context.close());
  // Basemap eksternal tidak diperlukan untuk menguji layer data dan interaksi mock.
  await context.route(/tiles\.openfreemap\.org/, (route) => route.abort());
  const page = await context.newPage();
  const errors = [];
  const apiRequests = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("request", (request) => { if (new URL(request.url()).pathname.startsWith("/api/")) apiRequests.push(request.url()); });
  await page.goto(`${baseURL}/masyarakat`);
  await page.waitForURL((url) => url.pathname === "/login");
  await signIn(page, baseURL, "community");
  await page.waitForURL("**/masyarakat");
  await page.getByRole("heading", { name: "Pantau hutan, jaga kehidupan" }).waitFor();
  assert.equal(await page.locator("aside nav a").count(), 1);
  assert.equal(await page.getByRole("button", { name: "Terkini", exact: true }).count(), 0);
  const inbox = page.getByRole("region", { name: "Peringatan wilayah", exact: true });
  assert.equal(await inbox.getByText("Baru", { exact: true }).count(), 3);
  await inbox.getByRole("button", { name: /Indikasi perubahan tutupan lahan/ }).click();
  await page.getByRole("heading", { name: "Indikasi perubahan tutupan lahan", exact: true }).waitFor();
  assert.equal(await inbox.getByText("Dibaca", { exact: true }).count(), 1);
  await page.reload();
  await page.getByRole("button", { name: "Tandai semua dibaca" }).waitFor({ state: "visible" });
  await page.waitForFunction(() => JSON.parse(localStorage.getItem("gambutops:community-store:v1"))?.read_alert_ids.length === 1);
  await inbox.getByText("Dibaca", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Tandai semua dibaca" }).click();
  assert.equal(await inbox.getByText("Dibaca", { exact: true }).count(), 3);
  const map = page.locator("main [data-map-status]");
  await page.waitForFunction(() => document.querySelector("main [data-map-status]")?.getAttribute("data-map-status") === "ready");
  await page.getByLabel("Deskripsi kejadian").fill("Asap terlihat di lahan contoh dekat kebun warga.");
  await page.getByRole("button", { name: "Simpan laporan simulasi" }).click();
  await page.getByRole("alert").filter({ hasText: "Pilih lokasi kejadian" }).waitFor();
  await page.getByRole("button", { name: "Pilih lokasi laporan", exact: true }).click();
  const canvas = map.locator("canvas");
  const canvasBounds = await canvas.boundingBox();
  assert.ok(canvasBounds);
  await canvas.click({ position: { x: canvasBounds.width / 2, y: canvasBounds.height / 2 } });
  await page.getByRole("button", { name: "Pilih lokasi laporan", exact: true }).waitFor();
  await page.getByRole("button", { name: "Simpan laporan simulasi" }).click();
  const history = page.getByRole("region", { name: "Laporan saya", exact: true });
  await history.getByText("Asap terlihat di lahan contoh dekat kebun warga.", { exact: true }).waitFor();
  await page.reload();
  await history.getByText("Asap terlihat di lahan contoh dekat kebun warga.", { exact: true }).waitFor();
  await page.screenshot({ path: "/tmp/peatsignal-community-desktop.png", fullPage: true });
  await selectOption(page.getByLabel("Wilayah pantauan"), { label: "Kubu Raya, Kalimantan Barat" });
  await history.getByText("Belum ada laporan.", { exact: false }).waitFor();
  assert.equal(await inbox.getByText("Baru", { exact: true }).count(), 3);
  await page.goto(`${baseURL}/tasks`);
  await page.waitForURL("**/masyarakat");
  await switchRole(page, "coordinator");
  await page.waitForURL("**/dashboard");
  await page.getByRole("heading", { name: "Ringkasan pemantauan", exact: true }).waitFor();
  assert.equal(await page.locator("aside").getByRole("link", { name: "Ruang masyarakat" }).count(), 0);
  assert.deepEqual(apiRequests, []);
  assert.deepEqual(errors, []);
});

test("masyarakat: mobile 320px, fallback WebGL, lokasi alternatif, dan waktu di masa depan", { timeout: 120_000 }, async (t) => {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 320, height: 850 } });
  t.after(() => context.close());
  await context.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (type, ...args) { return String(type).startsWith("webgl") ? null : original.call(this, type, ...args); };
  });
  const page = await context.newPage();
  await signIn(page, baseURL, "community", "/masyarakat");
  await page.getByText("Peta tidak dapat ditampilkan", { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole("button", { name: "Buka navigasi" }).click();
  const drawer = page.getByRole("dialog", { name: "Navigasi PeatSignal" });
  await drawer.getByRole("link", { name: "Ruang masyarakat", exact: true }).click();
  await drawer.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "Gunakan pusat wilayah (demo)" }).click();
  await page.getByLabel("Deskripsi kejadian").fill("Contoh laporan pembukaan lahan dari warga.");
  await page.getByLabel("Waktu kejadian").fill("2099-01-01T10:00");
  await page.getByRole("button", { name: "Simpan laporan simulasi" }).click();
  await page.getByRole("alert").filter({ hasText: "Waktu kejadian tidak boleh di masa depan" }).waitFor();
  await page.getByLabel("Waktu kejadian").fill("2026-10-12T10:00");
  await page.getByRole("button", { name: "Simpan laporan simulasi" }).click();
  await page.getByRole("region", { name: "Laporan saya" }).getByText("Contoh laporan pembukaan lahan dari warga.", { exact: true }).waitFor();
  await page.screenshot({ path: "/tmp/peatsignal-community-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
});
