import assert from "node:assert/strict";
import test from "node:test";
import { chromium } from "playwright";
import { chooseAccount, signOut } from "./helpers.mjs";

const baseURL = process.env.SHELL_BASE_URL ?? "http://127.0.0.1:3000";

test("laporan warga → koordinator → penanganan → selesai → warga, persisten dan sinkron antartab", { skip: process.env.COMMUNITY_E2E_REST !== "1", timeout: 120_000 }, async (t) => {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  t.after(() => context.close());
  const coordinator = { id: "coordinator-server", role: "coordinator", display_name: "Koordinator Backend" };
  const officer = { id: "officer-server", role: "field_officer", display_name: "Petugas Backend" };
  let role = "coordinator";
  const writes = [];
  const errors = [];
  await context.route("**/api/v1/**", (route) => {
    const request = route.request();
    if (request.method() !== "GET") writes.push(request.url());
    const path = new URL(request.url()).pathname;
    if (path.endsWith("/users")) return route.fulfill({ json: [coordinator, officer] });
    if (path.endsWith("/auth/me")) return route.fulfill({ json: role === "coordinator" ? coordinator : officer });
    if (path.endsWith("/tasks")) return route.fulfill({ json: [] });
    return route.fulfill({ status: 503, json: { detail: "API pengujian tidak menyediakan modul ini" } });
  });
  await context.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (type, ...args) { return String(type).startsWith("webgl") ? null : original.call(this, type, ...args); };
  });
  const page = await context.newPage();
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${baseURL}/login`);
  await chooseAccount(page, "community");
  await page.waitForURL("**/masyarakat");
  await page.getByRole("button", { name: "Gunakan pusat wilayah", exact: true }).click();
  const description = "Asap terlihat di kebun dekat permukiman warga.";
  await page.getByLabel("Deskripsi kejadian").fill(description);
  await page.getByLabel("Kontak (opsional)", { exact: true }).fill("081234567890");
  await page.getByRole("button", { name: "Simpan laporan", exact: true }).click();
  await page.getByRole("region", { name: "Laporan saya" }).getByText("Menunggu penanganan", { exact: true }).waitFor();
  await signOut(page);
  await page.goto(`${baseURL}/login?next=/laporan-masyarakat`);
  await chooseAccount(page, "coordinator");
  await page.waitForURL("**/laporan-masyarakat");
  await page.locator("aside").getByRole("link", { name: "Laporan masyarakat", exact: true }).waitFor();
  const list = page.getByRole("region", { name: "Daftar laporan masyarakat", exact: true });
  const detail = page.getByRole("region", { name: "Detail laporan masyarakat", exact: true });
  await list.getByRole("button", { name: /Asap terlihat/ }).click();
  await detail.getByText("081234567890", { exact: true }).waitFor();
  const observer = await context.newPage();
  observer.on("pageerror", (error) => errors.push(error.message));
  await observer.goto(`${baseURL}/laporan-masyarakat`);
  await observer.getByRole("region", { name: "Daftar laporan masyarakat" }).getByText("Menunggu penanganan", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Simpan penanganan", exact: true }).click();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("gambutops:community-store:v1")).reports[0].status), "SUBMITTED", "catatan kosong tidak disimpan");
  await page.getByLabel("Catatan penanganan", { exact: true }).fill("Pemeriksaan lokasi sedang dilakukan.");
  await page.getByRole("button", { name: "Simpan penanganan", exact: true }).click();
  await observer.getByRole("region", { name: "Daftar laporan masyarakat" }).getByText("Dalam penanganan", { exact: true }).waitFor();
  await observer.close();
  await page.reload();
  await list.getByRole("button", { name: /Asap terlihat/ }).click();
  await detail.getByText("Pemeriksaan lokasi sedang dilakukan.", { exact: true }).waitFor();
  await page.getByLabel("Catatan penanganan", { exact: true }).fill("Lokasi telah ditangani dan pemeriksaan selesai.");
  await page.getByRole("button", { name: "Simpan penanganan", exact: true }).click();
  await detail.getByText("Penanganan laporan telah selesai.", { exact: true }).waitFor();
  await page.setViewportSize({ width: 320, height: 850 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await signOut(page);
  await chooseAccount(page, "community");
  await page.waitForURL("**/masyarakat");
  const history = page.getByRole("region", { name: "Laporan saya", exact: true });
  await history.getByText("Lokasi telah ditangani dan pemeriksaan selesai.", { exact: true }).waitFor();
  await page.reload();
  await history.getByText("Pemeriksaan lokasi sedang dilakukan.", { exact: true }).waitFor();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem("gambutops:community-store:v1")));
  assert.equal(stored.reports[0].status, "RESOLVED");
  assert.equal(stored.reports[0].handling_history.length, 2);
  assert.equal(stored.reports[0].handling_history[0].actor_id, coordinator.id);
  await signOut(page);
  role = "field_officer";
  await page.goto(`${baseURL}/login?next=/tasks`);
  await chooseAccount(page, "field_officer");
  await page.waitForURL("**/tasks");
  assert.equal(await page.locator("aside").getByRole("link", { name: "Laporan masyarakat", exact: true }).count(), 0);
  await page.goto(`${baseURL}/laporan-masyarakat`);
  await page.waitForURL("**/dashboard");
  assert.deepEqual(writes, [], "penanganan masyarakat tidak menulis ke backend");
  assert.deepEqual(errors, []);
});
